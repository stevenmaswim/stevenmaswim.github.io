def runs(rows, ch):
    """One path rectangle per horizontal run of `ch`."""
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == ch:
                start = x
                while x < len(row) and row[x] == ch:
                    x += 1
                out.append(f"M{start} {y}h{x - start}v1h-{x - start}z")
            else:
                x += 1
    return "".join(out)


def svg(rows):
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), "grids are 16x16"
    assert set("".join(rows)) <= set("#-."), "use only # - ."
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">']
    if "-" in "".join(rows):
        parts.append(f'<path fill="{PAPER}" d="{runs(rows, "-")}"/>')
    parts.append(f'<path fill="{INK}" d="{runs(rows, "#")}"/>')
    parts.append("</svg>")
    return "".join(parts) + "\n"


